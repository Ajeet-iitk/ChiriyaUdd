export function makeI18n(){
  let lang = "en";
  return {
    get lang(){ return lang; },
    set(next){
      if(!I18N[next]) return;
      lang = next;
      document.documentElement.dataset.lang = next;
      document.documentElement.lang = LANGS.find(l => l.id === next)?.htmlLang || "en";
    },
    t(key, vars){
      let s = I18N[lang]?.[key];
      if(s == null) s = I18N.en[key];
      if(s == null) return key;
      if(vars) for(const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
      return s;
    },
    raw(key){ return I18N[lang]?.[key] ?? I18N.en[key]; },
    pick(arr){ return Array.isArray(arr) ? arr[Math.floor(Math.random() * arr.length)] : arr; },
  };
}
